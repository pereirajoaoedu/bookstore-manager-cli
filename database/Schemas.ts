// #region Selects

export const ListarAutores = `
    SELECT 
      AUT.AUT_ID AS ID, 
      AUT.AUT_NOME AS NOME, 
      TO_CHAR(AUT_DATA_NASCIMENTO,'DD/MM/YYYY') AS DATA_NASCIMENTO, 
      AUT.AUT_RESUMO AS RESUMO,
      AUT.AUT_ATIVO AS ATIVO
    FROM AUTOR AUT
    ORDER BY AUT.AUT_NOME;
`;

export const ListarAutorPorId = `
    SELECT
      AUT.AUT_ID AS ID, 
      AUT.AUT_NOME AS NOME, 
      TO_CHAR(AUT_DATA_NASCIMENTO,'DD/MM/YYYY') AS DATA_NASCIMENTO, 
      AUT.AUT_RESUMO AS RESUMO,
      AUT.AUT_ATIVO AS ATIVO
    FROM AUTOR AUT
    WHERE AUT.AUT_ID = $1;
`;

export const ListarLivros = `
    SELECT
      LIV.LIV_ID AS ID,
      LIV.LIV_TITULO AS TITULO,
      AUT.AUT_ID AS ID_AUTOR,
      AUT.AUT_NOME AS NOME_AUTOR,
      TO_CHAR(LIV.LIV_DATA_PUBLICACAO,'DD/MM/YYYY') AS DATA_PUBLICACAO,
      LIV.LIV_NUMERO_PAGINAS AS NUMERO_PAGINAS,
      LIV.LIV_ISBN AS ISBN,
      LIV.LIV_ATIVO AS ATIVO
    FROM LIVRO LIV
    INNER JOIN AUTOR AUT ON LIV.LIV_AUT_ID = AUT.AUT_ID
    ORDER BY LIV.LIV_TITULO;
`;

export const ListarLivroPorId = `
    SELECT
      LIV.LIV_ID AS ID,
      LIV.LIV_TITULO AS TITULO,
      AUT.AUT_ID AS ID_AUTOR,
      AUT.AUT_NOME AS NOME_AUTOR,
      TO_CHAR(LIV.LIV_DATA_PUBLICACAO,'DD/MM/YYYY') AS DATA_PUBLICACAO,
      LIV.LIV_NUMERO_PAGINAS AS NUMERO_PAGINAS,
      LIV.LIV_ISBN AS ISBN,
      LIV.LIV_ATIVO AS ATIVO
    FROM LIVRO LIV
    INNER JOIN AUTOR AUT ON LIV.LIV_AUT_ID = AUT.AUT_ID
    WHERE LIV.LIV_ID = $1;
`;

